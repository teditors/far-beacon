/* The look (commission 6): how a place looks is data, like everything else. A look is a small palette and a few
   numbers of style; the view (src/view/look.js) builds the one in force from layers, in this order:

     base -> the climate (by day) -> the world's own variation of it -> a rare look (a world or a country all in sepia,
     all in reds...) -> another world's style and palette -> the year -> the great trouble (faintly, everywhere) -> a
     curse on this country -> the country's rare trait -> the weather -> dusk -> night

   Each layer names only what it changes, with k: how far it pulls the look toward itself (1: all the way).

   Colours ('#rrggbb'):
     zenith, horizon  the sky, overhead and at the horizon; the fog is the horizon's colour unless it says otherwise
     fog              what far things fade into
     sun, shade       the sun's light, and the sky's light that fills the shade (cool, against a warm sun)
     bounce           light thrown back up from the ground
     cloud            the clouds' colour
     lift, gain       the colour grade: what the darks lean toward, and what the lights lean toward
     ink              outlines and ink lines
   Numbers:
     sunK, fillK      how strong the sun and the sky's fill light are (1 as made)
     sat, contrast    the colour grade's saturation and contrast (1 as drawn)
     bands, soft      toon shading: light in this many bands, with edges this soft (0 hard to 1 smooth)
     reach            how far the eye sees, against the usual
     line             ink lines on everything, land included: 0 none, 1 full (other worlds)
     outline          the strength of the outlines on people, creatures and nearby things
     paper            a painted grain over the picture
     vignette         the corners darkened
   ART.md says how to choose them. */
